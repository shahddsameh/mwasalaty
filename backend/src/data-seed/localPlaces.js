export function normalizePlaceName(place) {
  return String(place ?? '')
    .trim()
    .toLowerCase()
    .replace(/[-_]+/g, ' ')
    .replace(/\s+/g, ' ');
}

function entries(names, coordinates) {
  return Object.fromEntries(names.map((name) => [name, coordinates]));
}

